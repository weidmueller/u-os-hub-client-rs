TARGET=$1

set -euo pipefail

# Where the compiled example executables will be placed on the target device
EXECUTABLE_DIR="/opt"

# Where the systemd service files will be placed on the target device
SYSTEMD_SERVICE_DIRECTORY="/etc/systemd/system"

# List of services to build and deploy
SERVICES="u-os-hub-example-provider u-os-hub-example-consumer"

# Important paths
WATCH_DIR="/var/lib/u-os-iam/oauth-clients"
HASH_SCRIPT="/usr/sbin/generate-pbkdf2-sha256-hash.sh"
CREDENTIAL_STORE="/etc/credstore.encrypted"

# Function to print usage information
print_usage() {
    echo ""
    echo "Usage:"
    echo "  $0 TARGET"
    echo ""
    echo "User must have administrative rights on the remote device."
    echo ""
    echo "Target examples:"
    echo "  'ucu', 'ucg', 'ucm' and 'x86_64' which got mapped to the cargo target"
    echo ""
    echo "  Or the cargo targets direct:"
    echo "    aarch64-unknown-linux-gnu   - arm64 (ucu)"
    echo "    armv7-unknown-linux-gnueabihf - arm32 (ucm, ucg)"
    echo "    x86_64-unknown-linux-gnu    - x86_64"
    exit 1
}

if [ "$EUID" -ne 0 ]; then
    echo "Please run as root or with sudo"
    exit 1
fi

if [ -z "$TARGET" ]; then
    echo "Error: Missing target"
    print_usage
    exit 1
fi

if [ ! -x "$HASH_SCRIPT" ]; then
    echo "Error: The required IAM hash script is missing or not executable: '$HASH_SCRIPT'. Deploying the examples requires u-OS version 2.12 or later." >&2
    exit 1
fi

if [ "$TARGET" = "ucu" ]; then
    TARGET="aarch64-unknown-linux-gnu"
elif [ "$TARGET" = "ucm" ] || [ "$TARGET" = "ucg" ]; then
    TARGET="armv7-unknown-linux-gnueabihf"
elif [ "$TARGET" = "x86_64" ]; then
    TARGET="x86_64-unknown-linux-gnu"
fi

# Function to create an IAM drop-in machine client and store its credentials securely
# Arguments:
#   $1 - client name
#   $2 - scope
create_machine_client() (
    local client_name=$1
    local scope=$2
    local client_secret secret_hash client_file

    echo "Creating client: ${client_name}"

    client_secret=$(openssl rand -hex 32)
    secret_hash=$(printf '%s' "$client_secret" | "$HASH_SCRIPT")

    client_file=$(mktemp "${WATCH_DIR}/.${client_name}.XXXXXX")
    trap 'rm -f -- "$client_file"' EXIT

    jq -n \
        --arg id "$client_name" \
        --arg secret "$secret_hash" \
        --arg scope "$scope" \
        '{
            id: $id,
            redirectUrl: [],
            postLogoutRedirectURL: [],
            applicationType: "web",
            authMethod: "client_secret_basic",
            loginUrl: "",
            responseTypes: [],
            grantTypes: ["client_credentials"],
            accessTokenType: "bearer",
            idTokenUserinfoClaimsAssertion: true,
            clockSkew: 0,
            scopeWhitelist: ($scope | [scan("\\S+")]),
            grantAllScopes: false,
            addType: "ClientAutoGenerated",
            secret: $secret
        }' > "$client_file"

    printf 'CLIENT_ID=%s\nCLIENT_SECRET=%s\n' "$client_name" "$client_secret" \
        | systemd-creds encrypt -H - "${CREDENTIAL_STORE}/${client_name}.creds" --name="${client_name}"

    chmod 644 "$client_file"
    mv -f -- "$client_file" "${WATCH_DIR}/${client_name}.json"
)

# Create credentials for NATS and publish the clients to IAM's watch directory
echo "--> Generate credentials"
mkdir -p "$WATCH_DIR" "$CREDENTIAL_STORE"
chmod 755 "$WATCH_DIR"
create_machine_client "u_os_hub_example_provider" "hub.variables.provide"
create_machine_client "u_os_hub_example_consumer" "hub.variables.readwrite"

echo "--> Stop the $SERVICES"
systemctl stop $SERVICES 2>/dev/null || true

echo "--> Move files from /tmp to their final locations"
for service in $SERVICES; do
    mv /tmp/$service $EXECUTABLE_DIR/$service
    mv /tmp/$service.service $SYSTEMD_SERVICE_DIRECTORY/$service.service
done

echo "--> Overwrite file permissions"
for service in $SERVICES; do
    chmod +x $EXECUTABLE_DIR/$service
done

echo "--> Reload systemd"
systemctl daemon-reload

echo "--> Enable and start the services"
systemctl enable --now $SERVICES
